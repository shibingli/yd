// icon_test.go — the bundled icon sprite and its template reference contract.
// icon_test.go — 随包图标 sprite 及其模板引用契约。
package web_test

import (
	"strings"
	"testing"

	"github.com/shibingli/yd/web"
)

// TestIconPartialUsesTheBundledSprite pins the icon contract: templates reference one shared
// partial, the partial resolves the embedded sprite through the asset helper, and the sprite is
// actually embedded. | TestIconPartialUsesTheBundledSprite 固定图标契约：模板引用同一个共享片段，
// 片段经 asset 助手解析内嵌 sprite，且 sprite 确实被内嵌。
func TestIconPartialUsesTheBundledSprite(t *testing.T) {
	partial := string(readEmbedded(t, web.FS(), "templates/partials/icon.html"))
	for _, want := range []string{
		`asset "/static/img/icons.svg"`,
		`data-yd-icon="{{ . }}"`,
		`class="yd-icon"`,
		`aria-hidden="true"`,
	} {
		if !strings.Contains(partial, want) {
			t.Errorf("partials/icon.html is missing %q | partials/icon.html 缺少 %q", want, want)
		}
	}

	sprite := string(readEmbedded(t, web.FS(), "static/img/icons.svg"))
	for _, want := range []string{
		"Code generated by yd icons sync",
		`id="i-lucide-log-in"`,
		`id="i-lucide-log-out"`,
		`id="i-lucide-languages"`,
		`id="i-lucide-sun"`,
		`id="i-lucide-moon"`,
		`id="i-lucide-monitor"`,
	} {
		if !strings.Contains(sprite, want) {
			t.Errorf("embedded sprite is missing %q | 内嵌 sprite 缺少 %q", want, want)
		}
	}
}

// TestRequestedButtonsUseIcons pins the visual unification: the four requested actions render the
// shared icon partial rather than an ad-hoc glyph or inline SVG. | TestRequestedButtonsUseIcons
// 固定视觉统一：四类指定动作都渲染共享图标片段，而不是临时字符或内联 SVG。
func TestRequestedButtonsUseIcons(t *testing.T) {
	cases := []struct {
		file string
		icon string
	}{
		{"templates/pages/login.html", "lucide-log-in"},
		{"templates/partials/topbar.html", "lucide-log-out"},
		{"templates/partials/sidebar.html", "lucide-log-out"},
		{"templates/partials/topbar.html", "lucide-sun"},
		{"templates/partials/topbar.html", "lucide-moon"},
		{"templates/partials/topbar.html", "lucide-monitor"},
		{"templates/partials/lang-toggle.html", "lucide-languages"},
	}
	for _, tc := range cases {
		body := string(readEmbedded(t, web.FS(), tc.file))
		needle := `template "partials/icon" "` + tc.icon + `"`
		if !strings.Contains(body, needle) {
			t.Errorf("%s is missing %s | %s 缺少 %s", tc.file, needle, tc.file, needle)
		}
	}
}

// TestEditorToolbarUsesLucideSprite pins the editor contract: EasyMDE's runtime toolbar clones
// icons from a server-rendered Lucide palette, and no Font Awesome class or asset remains.
// TestEditorToolbarUsesLucideSprite 固定编辑器契约：EasyMDE 的运行时工具栏从服务端渲染的 Lucide
// 调色板克隆图标，且不再保留任何 Font Awesome 类名或资源。
func TestEditorToolbarUsesLucideSprite(t *testing.T) {
	icons := []string{
		"lucide-bold", "lucide-italic", "lucide-heading", "lucide-strikethrough",
		"lucide-quote", "lucide-list", "lucide-list-ordered", "lucide-link",
		"lucide-image", "lucide-code", "lucide-table", "lucide-minus",
		"lucide-eye", "lucide-columns-2", "lucide-maximize", "lucide-undo-2", "lucide-redo-2",
	}
	palette := string(readEmbedded(t, web.FS(), "templates/partials/editor-icons.html"))
	for _, icon := range icons {
		needle := `template "partials/icon" "` + icon + `"`
		if !strings.Contains(palette, needle) {
			t.Errorf("editor palette is missing %s | 编辑器调色板缺少 %s", needle, needle)
		}
		if !strings.Contains(palette, `data-yd-editor-icon="`+icon+`"`) {
			t.Errorf("editor palette does not expose %s to the decorator | 编辑器调色板未向装饰器暴露 %s", icon, icon)
		}
	}
	if !strings.Contains(palette, "data-yd-editor-icons") {
		t.Error("editor palette lacks its root marker | 编辑器调色板缺少根标记")
	}

	kit := string(readEmbedded(t, web.FS(), "static/js/yd-ui.js"))
	for _, want := range []string{"decorateEditorToolbar", "data-yd-editor-icons", "data-yd-editor-icon"} {
		if !strings.Contains(kit, want) {
			t.Errorf("yd-ui.js is missing %q | yd-ui.js 缺少 %q", want, want)
		}
	}
	for _, file := range []string{"static/js/yd-ui.js", "static/js/yd-message-editor.js"} {
		body := string(readEmbedded(t, web.FS(), file))
		if strings.Contains(body, `"fa fa-`) {
			t.Errorf("%s still assigns Font Awesome toolbar classes | %s 仍在分配 Font Awesome 工具栏类名", file, file)
		}
	}
	editor := string(readEmbedded(t, web.FS(), "static/js/yd-message-editor.js"))
	if !strings.Contains(editor, "decorateEditorToolbar") {
		t.Error("yd-message-editor.js does not decorate its toolbar | yd-message-editor.js 未装饰其工具栏")
	}
}
