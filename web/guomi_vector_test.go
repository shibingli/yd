// 签名的条目其 SM2 随机数取自 crypto/rand，无法注入，因此只经临时目录交换，绝不进入仓库。
//
// Node is optional: the tests that need it skip with an explicit reason when it is absent, and the
// determinism guard falls back to the checked-in data. | Node 是可选的：需要它的测试在缺失时带明确
