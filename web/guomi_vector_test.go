//   - TestGuomiJSVectors regenerates the vectors, writes them together with the entries that
//     cannot be checked in into a t.TempDir() and runs the Node suite over them; | TestGuomiJSVectors
//     重新生成向量，把它们与无法签入的条目一起写入 t.TempDir()，随后运行消费这些文件的 Node 套件；
//   - TestJSVectorsAcceptedByGo reads the JavaScript artefact from that temporary directory and
//     verifies every entry with the Go primitives; | TestJSVectorsAcceptedByGo 从该临时目录读取 JS
//     产物，用 Go 原语校验全部条目；
//   - TestFixturesAreDeterministic proves the regenerated bytes equal the checked-in fixtures
