// writeVectorFile stores vectors on disk exactly as the checked-in fixtures are formatted. | writeVectorFile 按签入夹具的格式把向量落盘。
func writeVectorFile(t *testing.T, path string, vectors guomiVectorFile) {
	t.Helper()

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("%v: %s: %v", errVectorIO, path, err)
	}
	if err := os.WriteFile(path, marshalVectors(t, vectors), 0o644); err != nil {
		t.Fatalf("%v: %s: %v", errVectorIO, path, err)
	}
}

// marshalVectors renders vectors with indentation and a trailing newline. | marshalVectors 以缩进加尾换行的形式渲染向量。
func marshalVectors(t *testing.T, vectors guomiVectorFile) []byte {
	t.Helper()

	raw, err := json.MarshalIndent(vectors, "", "  ")
	if err != nil {
		t.Fatalf("%v: %v", errVectorIO, err)
	}
	return append(raw, '\n')
}

// compareFixture fails unless the checked-in file equals the regenerated bytes, and names the
// switch that refreshes it so a deliberate vector change stays a one-command update. | compareFixture
// 在签入文件与重新生成的字节不一致时失败，并指出刷新用的开关，使有意变更向量时只需一条命令即可更新。
func compareFixture(t *testing.T, path string, want []byte) {
	t.Helper()

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v: %s: %v", errVectorIO, path, err)
	}
	if bytes.Equal(got, want) {
		return
	}
	t.Fatalf("%v: %s differs from the regenerated vectors; run %s=1 go test ./web/ -run TestFixturesAreDeterministic to refresh it | %v：%s 与重新生成的向量不一致；运行 %s=1 go test ./web/ -run TestFixturesAreDeterministic 以刷新",
		errVectorStale, path, envWriteFixtures, errVectorStale, path, envWriteFixtures)
}

// fixtureVectors is the part of either fixture file needed to prove it holds no random-k entry. | fixtureVectors 是证明任一夹具文件不含随机 k 条目所需的部分。
type fixtureVectors struct {
	// SM2 is the public key cryptography section. | SM2 是公钥密码段。
	SM2 sm2Vectors `json:"sm2"`

	// HtmxTransport exists only in the JavaScript vector file. | HtmxTransport 仅存在于 JS 向量文件中。
	HtmxTransport []htmxTransportVector `json:"htmxTransport"`
}

// assertFixtureHasFixedRandomisers rejects a fixture that still carries an entry whose randomiser
// came from crypto/rand: such an entry changes on every run and would dirty the working tree, which
// is exactly the regression this file guards against. | assertFixtureHasFixedRandomisers 拒绝仍带有
// 随机数来自 crypto/rand 条目的夹具：此类条目每次运行都会变化并弄脏工作区，正是本文件要防的回归。
func assertFixtureHasFixedRandomisers(t *testing.T, path string) {
	t.Helper()

	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v: %s: %v", errVectorIO, path, err)
	}
	var vectors fixtureVectors
	if err := json.Unmarshal(raw, &vectors); err != nil {
		t.Fatalf("%v: %s: %v", errVectorDecode, path, err)
	}
	for _, vector := range vectors.SM2.Encryptions {
		if vector.FixedKHex == "" {
			t.Errorf("%v: %s: sm2 encryption %q has no fixed randomiser | %v：%s：sm2 密文 %q 没有固定随机数", errVectorStale, path, vector.Name, errVectorStale, path, vector.Name)
		}
	}
	for _, vector := range vectors.SM2.Signatures {
		if vector.FixedKHex == "" {
			t.Errorf("%v: %s: sm2 signature %q has no fixed randomiser | %v：%s：sm2 签名 %q 没有固定随机数", errVectorStale, path, vector.Name, errVectorStale, path, vector.Name)
		}
	}
	if count := len(vectors.HtmxTransport); count != 0 {
		t.Errorf("%v: %s: htmxTransport carries %d payload(s) encrypted with a fresh randomiser | %v：%s：htmxTransport 含有 %d 条使用全新随机数加密的负载",
			errVectorStale, path, count, errVectorStale, path, count)
	}
}

// writeFixturesEnabled reports whether the suite may refresh the checked-in fixtures. | writeFixturesEnabled 报告套件是否可以刷新签入夹具。
func writeFixturesEnabled() bool {
	return os.Getenv(envWriteFixtures) == "1"
}

// deterministic returns the vectors without the entries whose randomiser came from crypto/rand, so
// the result is reproducible byte for byte and safe to check in. | deterministic 返回剔除随机数来自
// crypto/rand 的条目后的向量，因此结果逐字节可复现，可安全签入。
func (v guomiVectorFile) deterministic() guomiVectorFile {
	out := v
	out.SM2.Encryptions = make([]sm2EncryptionVector, 0, len(v.SM2.Encryptions))
	for _, vector := range v.SM2.Encryptions {
		if vector.FixedKHex != "" {
			out.SM2.Encryptions = append(out.SM2.Encryptions, vector)
		}
	}
	out.SM2.Signatures = make([]sm2SignatureVector, 0, len(v.SM2.Signatures))
	for _, vector := range v.SM2.Signatures {
		if vector.FixedKHex != "" {
			out.SM2.Signatures = append(out.SM2.Signatures, vector)
		}
	}
	return out
}

// buildGoVectors builds the Go side of the contract, asserting Go self-consistency on the way so a
// divergent vector never reaches the JavaScript side. | buildGoVectors 构建契约的 Go 侧，
// 并在过程中断言 Go 侧自洽，避免不一致的向量流入 JS 侧。
//
// withRandom adds the entries produced through the framework API, which draws its randomiser from
// crypto/rand, so they are exchanged through a temporary directory only. | withRandom 追加经框架 API
// 产出的条目，其随机数取自 crypto/rand，因此仅经临时目录交换。
func buildGoVectors(t *testing.T, withRandom bool) guomiVectorFile {
	t.Helper()

	privateKey, err := guomi.PrivateKeyFromHex(vectorPrivateKeyHex)
	if err != nil {
		t.Fatalf("private key | 私钥: %v", err)
	}
	publicKey := privateKey.Public()
	publicKeyHex := guomi.PublicKeyToHex(publicKey)
	if publicKeyHex != "04"+vectorPublicXHex+vectorPublicYHex {
		t.Fatalf("derived public key %s does not match the GB/T 32918.5 example point | 推导公钥 %s 与 GB/T 32918.5 算例点不一致", publicKeyHex, publicKeyHex)
	}

	return guomiVectorFile{
		Version:     1,
		GeneratedBy: "go",
		Note:        "regenerate with: YD_GUOMI_WRITE_FIXTURES=1 go test ./web/ -run TestFixturesAreDeterministic | 重新生成：YD_GUOMI_WRITE_FIXTURES=1 go test ./web/ -run TestFixturesAreDeterministic",
		SM3:         goSM3Vectors(),
		SM2: sm2Vectors{
			PrivateKeyHex:   vectorPrivateKeyHex,
			PublicKeyHex:    publicKeyHex,
			PublicKeyRawHex: publicKeyHex[2:],
			Layout:          ciphertextLayout,
			Encryptions:     goSM2Encryptions(t, publicKey, privateKey, withRandom),
			Signatures:      goSM2Signatures(t, privateKey, publicKey, withRandom),
		},
		SM4: goSM4Vectors(t),
	}
}

// goSM3Vectors returns the SM3 digest vectors, covering the official examples and the
// padding boundaries at 55, 56, 63, 64 and 65 bytes. | goSM3Vectors 返回 SM3 摘要向量，
// 覆盖官方向量与 55、56、63、64、65 字节的填充边界。
func goSM3Vectors() []sm3Vector {
	repeated := strings.Repeat("abcd", 64)
	inputs := []struct{ name, text string }{
		{"abc GB/T 32905", "abc"},
		{"empty", ""},
		{"abcd-x64 GB/T 32905", repeated},
		{"utf8 CJK | 中文", "国密 SM3 沙箱 | guomi sandbox"},
		{"len-55", strings.Repeat("a", 55)},
		{"len-56", strings.Repeat("a", 56)},
		{"len-63", strings.Repeat("a", 63)},
		{"len-64", strings.Repeat("a", 64)},
		{"len-65", strings.Repeat("a", 65)},
		{"len-1000-ascii", strings.Repeat("yd", 500)},
	}
	vectors := make([]sm3Vector, 0, len(inputs)+1)
	for _, input := range inputs {
		data := []byte(input.text)
		vectors = append(vectors, sm3Vector{
			Name:      input.name,
			DataHex:   hex.EncodeToString(data),
			DataUtf8:  input.text,
			DigestHex: guomi.SumHex(data),
		})
	}
	// A binary vector covers bytes that are invalid UTF-8 and exercises the byte API only. | 二进制向量覆盖非法 UTF-8 字节，仅走字节 API。
	binary := make([]byte, 1000)
	for i := range binary {
		binary[i] = byte(i*7 + 1)
	}
	vectors = append(vectors, sm3Vector{Name: "len-1000-binary", DataHex: hex.EncodeToString(binary), DigestHex: guomi.SumHex(binary)})
	return vectors
}

// goSM2Encryptions returns raw C1C3C2 ciphertexts, deterministic for the fixed randomiser and
// random through guomi.EncryptRaw for the framework path. | goSM2Encryptions 返回原始 C1C3C2 密文：
// 固定随机数的确定性样本，以及走 guomi.EncryptRaw 的随机样本。
//
// The framework samples are returned only when withRandom is set, because crypto/rand cannot be
// pinned and they may therefore never leave the temporary directory. | 仅当 withRandom 为真时返回框架样本，
// 因为 crypto/rand 无法固定，它们因而绝不能离开临时目录。
func goSM2Encryptions(t *testing.T, publicKey *guomi.PublicKey, privateKey *guomi.PrivateKey, withRandom bool) []sm2EncryptionVector {
	t.Helper()

	plaintexts := []struct{ name, text string }{
		{"ascii", "yd sandbox login"},
		{"utf8 CJK | 中文", "国密前端沙箱 | guomi sandbox"},
	}
	var vectors []sm2EncryptionVector
	for _, plaintext := range plaintexts {
		vectors = append(vectors, deterministicEncryption(t, publicKey, privateKey, plaintext.name, []byte(plaintext.text)))
	}
	binary := []byte{0xff, 0x00, 0xff, 0x00, 0xa5, 0x5a, 0x00, 0x01}
	vectors = append(vectors, deterministicEncryption(t, publicKey, privateKey, "binary", binary))
	// 100 bytes cross the 32-byte KDF block boundary, which is where implementations diverge. | 100 字节跨越 32 字节 KDF 分块边界，正是各实现容易分歧之处。
	long := make([]byte, 100)
	for i := range long {
		long[i] = byte(i)
	}
	vectors = append(vectors, deterministicEncryption(t, publicKey, privateKey, "kdf-multi-block-100B", long))
	if !withRandom {
		return vectors
	}

	for _, plaintext := range []struct{ name, text string }{
		{"framework-encryptraw", "guomi.EncryptRaw | 框架原始密文"},
		{"framework-encryptraw-empty", ""},
	} {
		ciphertext, err := guomi.EncryptRaw(publicKey, []byte(plaintext.text))
		if err != nil {
			t.Fatalf("EncryptRaw(%s) | EncryptRaw(%s): %v", plaintext.name, plaintext.name, err)
		}
		// Round-trip here so the JavaScript side only ever sees verified bytes. | 此处先做往返校验，确保 JS 侧只看到已验证的字节。
		if back, err := guomi.DecryptRaw(privateKey, ciphertext); err != nil || string(back) != plaintext.text {
			t.Fatalf("EncryptRaw round-trip %s | EncryptRaw 往返 %s: %v", plaintext.name, plaintext.name, err)
		}
		vectors = append(vectors, sm2EncryptionVector{
			Name:      plaintext.name,
			PlainHex:  hex.EncodeToString([]byte(plaintext.text)),
			CipherHex: hex.EncodeToString(ciphertext),
			Layout:    ciphertextLayout,
		})
	}
	return vectors
}

// deterministicEncryption builds one raw ciphertext with the fixed randomiser and asserts that
// Go accepts it, so the layout claim is proven on the Go side first. | deterministicEncryption
// 使用固定随机数构造一条原始密文，并断言 Go 能接受它，从而先在 Go 侧坐实布局声明。
func deterministicEncryption(t *testing.T, publicKey *guomi.PublicKey, privateKey *guomi.PrivateKey, name string, plaintext []byte) sm2EncryptionVector {
	t.Helper()

	if len(plaintext) == 0 {
		// gmsm's kdf reports "all zero" for klen == 0, which makes Encrypt retry forever on a
		// fixed reader. The empty plaintext is therefore covered by EncryptRaw instead. | gmsm 的 kdf
		// 对 klen == 0 返回「全零」判定，这会让 Encrypt 在固定随机源上无限重试；空明文改由 EncryptRaw 覆盖。
		t.Fatalf("deterministic empty plaintext is unsupported by gmsm | gmsm 不支持确定性的空明文")
	}
	effective, stream := fixedRandomiser(t)
	// emmansun/gmsm emits one leading 0x04 marker byte that guomi.EncryptRaw does not use. | emmansun/gmsm 会多输出一个前导 0x04 标识字节，而 guomi.EncryptRaw 不使用它。
	ciphertext, err := esm2.Encrypt(&fixedReader{buf: stream}, publicKey.Raw(), plaintext,
		esm2.NewPlainEncrypterOpts(esm2.MarshalUncompressed, esm2.C1C3C2))
	if err != nil {
		t.Fatalf("gmsm Encrypt(%s) | gmsm Encrypt(%s): %v", name, name, err)
	}
	if len(ciphertext) == 0 || ciphertext[0] != 0x04 {
		t.Fatalf("gmsm Encrypt(%s) has no uncompressed point marker | gmsm Encrypt(%s) 缺少未压缩点标识", name, name)
	}
	raw := ciphertext[1:]
	if len(raw) != 2*guomi.SM2CoordinateSize+guomi.SM3Size+len(plaintext) {
		t.Fatalf("raw ciphertext length %d, want %d | 原始密文长度 %d，期望 %d", len(raw), 2*guomi.SM2CoordinateSize+guomi.SM3Size+len(plaintext), len(raw), 2*guomi.SM2CoordinateSize+guomi.SM3Size+len(plaintext))
	}
	back, err := guomi.DecryptRaw(privateKey, raw)
	if err != nil {
		t.Fatalf("guomi.DecryptRaw(%s) | guomi.DecryptRaw(%s): %v", name, name, err)
	}
	if string(back) != string(plaintext) {
		t.Fatalf("guomi.DecryptRaw(%s) = %q, want %q | guomi.DecryptRaw(%s) 为 %q，期望 %q", name, back, plaintext, name, back, plaintext)
	}
	return sm2EncryptionVector{
		Name:      name,
		PlainHex:  hex.EncodeToString(plaintext),
		CipherHex: hex.EncodeToString(raw),
		FixedKHex: hex.EncodeToString(paddedBytes(effective, guomi.SM2CoordinateSize)),
		Layout:    ciphertextLayout,
	}
}

// fixedRandomiser returns the fixed scalar used by the deterministic encryption and the 32-byte
// stream handed to gmsm. For encryption the stream is the scalar itself; for signing it is the
// hedged-DRBG entropy, and the actual nonce is recovered from the signature. | fixedRandomiser
// 返回确定性加密使用的固定标量，以及交给 gmsm 的 32 字节流。加密时该流就是标量本身；签名时它是
// 对冲 DRBG 的熵，实际随机数由签名反推。
//
// emmansun/gmsm reads c.N.Size() = 32 bytes for one nonce and uses the value directly when it is
// in [1, n-1], so the stream is the scalar itself. Recording it keeps the vectors reproducible
// from JavaScript with the single value it can consume. | emmansun/gmsm 每次随机数读取
// c.N.Size() = 32 字节，取值落在 [1, n-1] 内时直接作为标量使用，因此字节流就是标量本身。
// 记录该值使 JS 侧仅凭这一个可直接消费的数值即可复现向量。
func fixedRandomiser(t *testing.T) (*big.Int, []byte) {
	t.Helper()

	seed, ok := new(big.Int).SetString(vectorFixedKHex, 16)
	if !ok {
		t.Fatalf("fixed randomiser %q is not hex | 固定随机数 %q 不是合法十六进制", vectorFixedKHex, vectorFixedKHex)
	}

	order := esm2.P256().Params().N
	effective := new(big.Int).Mod(seed, new(big.Int).Sub(order, big.NewInt(1)))
	effective.Add(effective, big.NewInt(1))
	if effective.Sign() <= 0 || effective.Cmp(order) >= 0 {
		t.Fatalf("effective randomiser %s is outside [1, n-1] | 有效随机数 %s 超出 [1, n-1]", effective, effective)
	}
	return effective, paddedBytes(effective, fixedRandomSize)
}

// goSM2Signatures returns one deterministic DER signature plus, when withRandom is set, the
// signatures produced by guomi.Sign, which cannot be reproduced because their randomiser comes
// from crypto/rand. | goSM2Signatures 返回一条确定性 DER 签名，并在 withRandom 为真时追加由
// guomi.Sign 产生的签名；后者的随机数取自 crypto/rand，无法复现。
func goSM2Signatures(t *testing.T, privateKey *guomi.PrivateKey, publicKey *guomi.PublicKey, withRandom bool) []sm2SignatureVector {
	t.Helper()

	message := []byte("yd sandbox signature | 沙箱签名")
	_, stream := fixedRandomiser(t)
	der, err := privateKey.Raw().SignWithSM2(&fixedReader{buf: stream}, nil, message)
	if err != nil {
		t.Fatalf("gmsm SignWithSM2 | gmsm SignWithSM2: %v", err)
	}
	var sig derSignature
	if _, err := asn1.Unmarshal(der, &sig); err != nil {
		t.Fatalf("der signature | DER 签名: %v", err)
	}
	if ok, err := guomi.Verify(publicKey, message, der); err != nil || !ok {
		t.Fatalf("deterministic signature rejected by guomi.Verify | 确定性签名未被 guomi.Verify 接受: ok=%v err=%v", ok, err)
	}

	// Recover the nonce from the signature so JavaScript can reproduce it: SM2 defines
	// k = s*(1+d) + r*d (mod n). | 从签名反推随机数 k，供 JS 复现：SM2 定义 k = s*(1+d) + r*d (mod n)。
	order := esm2.P256().Params().N
	d := privateKey.Raw().D
	k := new(big.Int).Mul(sig.S, new(big.Int).Add(d, big.NewInt(1)))
	k.Add(k, new(big.Int).Mul(sig.R, d))
	k.Mod(k, order)
	if k.Sign() <= 0 || k.Cmp(order) >= 0 {
		t.Fatalf("recovered nonce %s is outside [1, n-1] | 反推的随机数 %s 超出 [1, n-1]", k, k)
	}

	vectors := []sm2SignatureVector{
		{
			Name:         "deterministic-fixed-k",
			DataHex:      hex.EncodeToString(message),
			SignatureHex: hex.EncodeToString(der),
			Algorithm:    signatureAlgorithm,
			FixedKHex:    hex.EncodeToString(paddedBytes(k, guomi.SM2CoordinateSize)),
		},
	}
	if !withRandom {
		return vectors
	}

	randomHex, err := guomi.SignHex(privateKey, message)
	if err != nil {
		t.Fatalf("guomi.SignHex | guomi.SignHex: %v", err)
	}
	if ok, err := guomi.VerifyHex(publicKey, message, randomHex); err != nil || !ok {
		t.Fatalf("framework signature rejected by guomi.Verify | 框架签名未被 guomi.Verify 接受: ok=%v err=%v", ok, err)
	}

	empty := []byte{}
	emptyHex, err := guomi.SignHex(privateKey, empty)
	if err != nil {
		t.Fatalf("guomi.SignHex(empty) | guomi.SignHex(空): %v", err)
	}

	return append(vectors,
		sm2SignatureVector{Name: "framework-Sign", DataHex: hex.EncodeToString(message), SignatureHex: randomHex, Algorithm: signatureAlgorithm},
		sm2SignatureVector{Name: "framework-Sign-empty", DataHex: "", SignatureHex: emptyHex, Algorithm: signatureAlgorithm},
	)
}

// goSM4Vectors returns CBC and GCM vectors, including a non-12-byte GCM nonce. | goSM4Vectors 返回 CBC 与 GCM 向量，含非 12 字节 GCM 随机数。
func goSM4Vectors(t *testing.T) sm4Vectors {
	t.Helper()

	key, err := hex.DecodeString(vectorSM4KeyHex)
	if err != nil {
		t.Fatalf("sm4 key | SM4 密钥: %v", err)
	}
	iv, err := hex.DecodeString(vectorSM4IVHex)
	if err != nil {
		t.Fatalf("sm4 iv | SM4 初始向量: %v", err)
	}
	nonce, err := hex.DecodeString(vectorSM4NonceHex)
	if err != nil {
		t.Fatalf("sm4 nonce | SM4 随机数: %v", err)
	}

	cbcPlaintexts := []struct {
		name string
		data []byte
	}{
		{"empty", []byte{}},
		{"block-16B", []byte("0123456789abcdef")},
		{"utf8 CJK | 中文", []byte("国密沙箱")},
		{"long-100B", make([]byte, 100)},
	}
	for i := range cbcPlaintexts[3].data {
		cbcPlaintexts[3].data[i] = byte(0xff - i)
	}
	vectors := sm4Vectors{KeyHex: vectorSM4KeyHex}
	for _, plaintext := range cbcPlaintexts {
		ciphertext, err := guomi.EncryptCBC(key, iv, plaintext.data)
		if err != nil {
			t.Fatalf("EncryptCBC(%s) | EncryptCBC(%s): %v", plaintext.name, plaintext.name, err)
		}
		if back, err := guomi.DecryptCBC(key, iv, ciphertext); err != nil || string(back) != string(plaintext.data) {
			t.Fatalf("DecryptCBC round-trip %s | DecryptCBC 往返 %s: %v", plaintext.name, plaintext.name, err)
		}
		vectors.CBC = append(vectors.CBC, sm4CBCVector{
			Name:      plaintext.name,
			IVHex:     vectorSM4IVHex,
			PlainHex:  hex.EncodeToString(plaintext.data),
			CipherHex: hex.EncodeToString(ciphertext),
		})
	}

	gcmInputs := []struct {
		name      string
		nonce     []byte
		aad       []byte
		plaintext []byte
	}{
		{"nonce-12-aad-empty-plain-empty", nonce, []byte{}, []byte{}},
		{"nonce-12-aad-5B-plain-16B", nonce, []byte{0x01, 0x23, 0x45, 0x67, 0x89}, []byte("0123456789abcdef")},
		{"nonce-12-aad-16B-plain-100B", nonce, []byte("0123456789abcdef"), make([]byte, 100)},
		{"nonce-12-aad-utf8-plain-37B", nonce, []byte("附加认证 | aad"), make([]byte, 37)},
		{"nonce-16-aad-utf8-plain-utf8", iv, []byte("aad"), []byte("non-96-bit nonce | 非 96 位随机数")},
	}
	for i := range gcmInputs[2].plaintext {
		gcmInputs[2].plaintext[i] = byte(i * 3)
	}
	for i := range gcmInputs[3].plaintext {
		gcmInputs[3].plaintext[i] = byte(i + 0x40)
	}
	for _, input := range gcmInputs {
		sealed, err := guomi.SealGCM(key, input.nonce, input.plaintext, input.aad)
		if err != nil {
			t.Fatalf("SealGCM(%s) | SealGCM(%s): %v", input.name, input.name, err)
		}
		if len(sealed) != len(input.plaintext)+guomi.SM4GCMTagSize {
			t.Fatalf("SealGCM(%s) length %d | SealGCM(%s) 长度 %d", input.name, len(sealed), input.name, len(sealed))
		}
		if back, err := guomi.OpenGCM(key, input.nonce, sealed, input.aad); err != nil || string(back) != string(input.plaintext) {
			t.Fatalf("OpenGCM round-trip %s | OpenGCM 往返 %s: %v", input.name, input.name, err)
		}
		vectors.GCM = append(vectors.GCM, sm4GCMVector{
			Name:      input.name,
			NonceHex:  hex.EncodeToString(input.nonce),
			AADHex:    hex.EncodeToString(input.aad),
			PlainHex:  hex.EncodeToString(input.plaintext),
			CipherHex: hex.EncodeToString(sealed),
		})
	}
	return vectors
}

// paddedBytes renders a big integer as a fixed width big-endian buffer. | paddedBytes 把大整数渲染为定长大端缓冲区。
func paddedBytes(x *big.Int, size int) []byte {
	out := make([]byte, size)
	raw := x.Bytes()
	if len(raw) >= size {
		copy(out, raw[len(raw)-size:])
		return out
	}
	copy(out[size-len(raw):], raw)
	return out
}

// runNodeTest executes the JavaScript suite with the vector paths from env, skipping the test when
// Node is unavailable. | runNodeTest 带着 env 中的向量路径执行 JS 套件，Node 不可用时跳过测试。
func runNodeTest(t *testing.T, env []string) ([]byte, error) {
	t.Helper()

	if _, err := exec.LookPath("node"); err != nil {
		t.Skipf("skipping: node is not available on PATH (%v); install Node.js to run the javascript guomi suite | 跳过：PATH 中没有 node（%v），请安装 Node.js 以运行 JS 国密套件", err, err)
		return nil, nil
	}

	script := ""
	for _, candidate := range []string{jsTestScriptName, "static/js/yd-guomi.test.mjs"} {
		if _, err := os.Stat(candidate); err == nil {
			script = candidate
			break
		}
	}
	if script == "" {
		t.Fatalf("%v: %s | 缺少 %s", errNodeScriptMissing, jsTestScriptName, jsTestScriptName)
		return nil, nil
	}

	cmd := exec.Command("node", script)
	// The vector paths travel by environment so no run has to guess where the other side put its
	// files; the inherited environment stays intact, hence the append onto a copy. | 向量路径通过环境变量传递，
	// 任一侧都不必猜测对方的文件位置；继承来的环境保持完整，故在副本上追加。
	cmd.Env = append(os.Environ(), env...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return out, errs.WrapDetail(err, errNodeRunFailed, "node %s exited with an error | node %s 以错误退出", script, script)
	}
	return out, nil
}
