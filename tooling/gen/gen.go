// Options 控制一次生成：输出位置、导入前缀与写入策略。
// Options controls one generation run: output location, import prefix and write policy.
type Options struct {
	// Module 是业务模块名，非空时覆盖 Model.Module，用作 OpenAPI 的 @Tags 与生成代码的文档上下文。
	// Module is the business module name; when set it overrides Model.Module and is used as the OpenAPI @Tags value and in generated doc text.
	Module string
	// Package 是目标工程的 Go 导入前缀（模块路径），生成物内部 import 时使用；为空时使用 FrameworkModule。
	// Package is the Go import prefix (module path) of the target project used by generated internal imports; FrameworkModule is used when empty.
	Package string
	// Dir 是输出根目录，生成物按 internal/... 与 web/templates/... 相对落盘；为空时写入 fs 根。
	// Dir is the output root: artifacts land under internal/... and web/templates/... below it; when empty they land at the fs root.
	Dir string
	// Force 允许覆盖没有生成标记的同名文件，默认关闭以免毁掉手写代码。
	// Force allows overwriting same-named files without the generated marker; it is off by default so hand-written code survives.
	Force bool
	// DryRun 只报告将要写入的文件与差异摘要，不落盘。
	// DryRun only reports the files that would be written plus a diff summary, without touching the filesystem.
	DryRun bool
}

// Result 是一次生成的文件清单：Written 是已写入（DryRun 时为将写入）的文件，
// Skipped 是刻意未改动的文件（内容一致，或受手写文件保护规则保护）。
// Result is the file inventory of one run: Written holds the files written (or to be
// written under DryRun), Skipped holds the files deliberately left untouched
// (identical content, or protected by the hand-written file rule).
//
// 路径一律为斜杠分隔的、相对 Options.Dir 的路径，与操作系统无关。
// Every path is slash separated and relative to Options.Dir, independent of the operating system.
type Result struct {
	// Written 是本次写入的文件路径。
	// Written lists the paths written by this run.
	Written []string
	// Skipped 是本次跳过的文件路径。
	// Skipped lists the paths skipped by this run.
	Skipped []string
}

// artifact 是一个待落盘的生成文件。
// artifact is one generated file waiting to be written.
type artifact struct {
	// rel 是相对 Options.Dir 的斜杠路径。
	// rel is the slash path relative to Options.Dir.
	rel string
	// content 是最终字节内容（.go 文件已格式化）。
	// content is the final byte content (.go files are already formatted).
	content []byte
	// merge 表示该文件按标记区块合并，不受手写文件保护规则约束。
	// merge marks a file merged through its marker block, which bypasses the hand-written file protection.
	merge bool
}

// Generate 渲染 m 的全部生成物并按写入策略落盘。
// Generate renders every artifact of m and writes them according to the write policy.
//
// ctx 用于中止耗时较长的生成；o 控制输出目录、导入前缀与写入策略；
// fs 是任意 afero 文件系统（OsFs、MemMapFs、BasePathFs 均可）。
// ctx aborts a long-running run; o controls the output directory, the import prefix
// and the write policy; fs is any afero filesystem (OsFs, MemMapFs, BasePathFs all work).
//
// 返回的 Result 永远非 nil（即使中途失败，也能拿到已处理的文件清单）。
// The returned Result is never nil, so callers can inspect the files already
// processed even when the run fails halfway.
func Generate(ctx context.Context, m *Model, o Options, fs afero.Fs) (*Result, error) {
	res := &Result{}
	if ctx == nil {
		ctx = context.Background()
	}
	if fs == nil {
		return res, ErrNilFS
	}
	if err := ctx.Err(); err != nil {
		return res, errs.Wrap(err, ErrCancelled)
	}
	if m == nil {
		return res, errs.Detail(ErrBadModel, "model is required | 模型不能为空")
	}

	// Only a scaffold target already defines User/Role/Tenant/Permission services, repositories
	// and model types; generating the same module name there would redeclare them and leave a
	// project that no longer builds. A bare directory has no such names and is left alone.
	// | 只有脚手架产物已经定义了 User/Role/Tenant/Permission 的服务、仓储与模型类型；在那里生成
	// 同名模块会重复声明并留下无法编译的项目。普通目录没有这些名字，因此不施加该限制。
	if reservedModuleNames[strings.ToLower(m.GoName)] &&
		afs.Exists(fs, o.fullPath(path.Join("internal", "meta", "meta.go"))) {
		return res, errs.Detail(ErrBadModel, "model name %[1]q collides with a scaffold-defined type; choose another name | 模型名 %[1]q 与脚手架已定义的类型冲突，请换一个名称", m.GoName)
	}
	v, err := newView(m, o)
	if err != nil {
		return res, err
	}

	arts, err := renderArtifacts(fs, o, v)
	if err != nil {
		return res, err
	}

	for _, art := range arts {
		if err := ctx.Err(); err != nil {
			return res, errs.Wrap(err, ErrCancelled)
		}
		if err := applyArtifact(fs, o, art, res); err != nil {
			return res, err
		}
	}
	return res, nil
}

// applyArtifact 决定单个生成物是写入还是跳过，并在非 DryRun 时落盘。
// applyArtifact decides whether one artifact is written or skipped, and writes it when not in DryRun.
func applyArtifact(fs afero.Fs, o Options, art artifact, res *Result) error {
	full := o.fullPath(art.rel)
	old, exists, err := readIfExists(fs, full)
	if err != nil {
		return errs.WrapDetail(err, ErrReadFile, "path=%[1]s | 路径=%[1]s", art.rel)
	}

	if exists {
		if bytes.Equal(old, art.content) {
			res.Skipped = append(res.Skipped, art.rel)
			return nil
		}
		if !art.merge && !o.Force && !hasGeneratedMarker(old) {
			log.Default().Warn("skipped a hand-written file without the generator marker | 跳过了没有生成标记的手写文件",
				log.Str("path", art.rel))
			res.Skipped = append(res.Skipped, art.rel)
			return nil
		}
	}

	if o.DryRun {
		log.Default().Info("dry run: file would be written | 试运行：将写入文件",
			log.Str("path", art.rel), log.Str("diff", diffSummary(old, art.content)))
		res.Written = append(res.Written, art.rel)
		return nil
	}

	if _, err := afs.WriteFileIfChanged(fs, full, art.content); err != nil {
		return errs.WrapDetail(err, ErrWriteFile, "path=%[1]s | 路径=%[1]s", art.rel)
	}
	log.Default().Info("generated file written | 已写入生成文件", log.Str("path", art.rel))
	res.Written = append(res.Written, art.rel)
	return nil
}

// fullPath 把斜杠相对路径拼成 fs 上的实际路径。
// fullPath joins a slash relative path into the real path on fs.
func (o Options) fullPath(rel string) string {
	if o.Dir == "" {
		return filepath.FromSlash(rel)
	}
	return filepath.Join(o.Dir, filepath.FromSlash(rel))
}

// readIfExists 读取 path 的既有内容；文件不存在时返回 (nil, false, nil)。
// readIfExists reads the existing content of path; it returns (nil, false, nil) when the file is absent.
func readIfExists(fs afero.Fs, path string) ([]byte, bool, error) {
	if !afs.Exists(fs, path) {
		return nil, false, nil
	}
	b, err := afero.ReadFile(fs, path)
	if err != nil {
		return nil, true, err
	}
	return b, true, nil
}

// hasGeneratedMarker 报告内容是否带生成标记（HTML 模板沿用同一条注释文本）。
// hasGeneratedMarker reports whether the content carries the generated marker (HTML templates reuse the same comment text).
func hasGeneratedMarker(content []byte) bool {
	return bytes.Contains(content, []byte(GeneratedMarker))
}

// renderArtifacts 渲染全部生成物：先逐文件渲染，再合并 routes_gen.go 的标记区块。
// renderArtifacts renders every artifact: file by file first, then the marker block of routes_gen.go.
func renderArtifacts(fs afero.Fs, o Options, v *tmplView) ([]artifact, error) {
	plan := []struct{ tmpl, rel string }{
		{"model.go.tmpl", path.Join("internal/model", v.Snake+".go")},
		{"repo.go.tmpl", path.Join("internal/repository", v.Snake+"_repo.go")},
		{"service.go.tmpl", path.Join("internal/service", v.Snake+"_service.go")},
		{"controller.go.tmpl", path.Join("internal/controller", v.Snake+"_controller.go")},
		{"routes.go.tmpl", path.Join("internal/router", v.Snake+"_routes.go")},
		{"list.html.tmpl", path.Join("web/templates", v.Snake, "list.html")},
		{"form.html.tmpl", path.Join("web/templates", v.Snake, "form.html")},
		{"row.html.tmpl", path.Join("web/templates", v.Snake, "row.html")},
		{"fields.html.tmpl", path.Join("web/templates", v.Snake, "_fields.html")},
	}

	arts := make([]artifact, 0, len(plan)+1)
	for _, p := range plan {
		content, err := renderTemplate(p.tmpl, v)
		if err != nil {
			return nil, err
		}
		if strings.HasSuffix(p.rel, ".go") {
			if content, err = formatSource(p.rel, content); err != nil {
				return nil, err
			}
		}
		arts = append(arts, artifact{rel: p.rel, content: content})
	}

	reg, err := mergeRoutesGen(fs, o, v)
	if err != nil {
		return nil, err
	}
	arts = append(arts, artifact{rel: routesGenPath, content: reg, merge: true})
	return arts, nil
}

// routesGenPath 是路由注册文件的固定位置。
// routesGenPath is the fixed location of the route registration file.
const routesGenPath = "internal/router/routes_gen.go"

// registeredModuleRe 匹配标记区块内的注册行，用于在重新生成时保留其它模块。
// registeredModuleRe matches the registration lines inside the marker block so other modules survive a regeneration.
var registeredModuleRe = regexpx.MustCompile(`Register([A-Za-z0-9_]+)Routes\(g, deps\.([A-Za-z0-9_]+)\)`)

// mergeRoutesGen 计算 routes_gen.go 的最终内容：缺文件则创建，存在则只替换标记区块。
// mergeRoutesGen computes the final content of routes_gen.go: it creates the file when absent and replaces only the marker block when present.
func mergeRoutesGen(fs afero.Fs, o Options, v *tmplView) ([]byte, error) {
	old, exists, err := readIfExists(fs, o.fullPath(routesGenPath))
	if err != nil {
		return nil, errs.WrapDetail(err, ErrReadFile, "path=%[1]s | 路径=%[1]s", routesGenPath)
	}

	rv := &routesGenView{tmplView: v, Modules: []moduleRef{{Name: v.Name, Snake: v.Snake}}}
	if exists {
		rv.Modules = mergeModuleRefs(rv.Modules, parseRegisteredModules(string(old)))
	}

	block, err := renderTemplate("routes_gen_block.tmpl", rv)
	if err != nil {
		return nil, err
	}

	var content []byte
	if exists {
		content = []byte(upsertMarkerBlock(string(old), string(block)))
	} else {
		full, err := renderTemplate("routes_gen.go.tmpl", &routesGenView{tmplView: v, Block: string(block)})
		if err != nil {
			return nil, err
		}
		content = full
	}
	return formatSource(routesGenPath, content)
}

// parseRegisteredModules 从既有 routes_gen.go 中解析出已经注册的模块名。
// parseRegisteredModules extracts the module names already registered in an existing routes_gen.go.
func parseRegisteredModules(src string) []moduleRef {
	matches := registeredModuleRe.FindAllStringSubmatch(src, -1)
	refs := make([]moduleRef, 0, len(matches))
	for _, m := range matches {
		refs = append(refs, moduleRef{Name: m[1], Snake: snakeCase(m[2])})
	}
	return refs
}

// mergeModuleRefs 把 already 中已有的模块合并进 cur，保持 cur 在前、按名称去重。
// mergeModuleRefs merges the modules of already into cur: cur keeps the lead and duplicates are dropped by name.
func mergeModuleRefs(cur, already []moduleRef) []moduleRef {
	seen := make(map[string]bool, len(cur))
	for _, r := range cur {
		seen[r.Name] = true
	}
	out := append([]moduleRef(nil), cur...)
	for _, r := range already {
		if r.Name == "" || seen[r.Name] {
			continue
		}
		seen[r.Name] = true
		out = append(out, moduleRef{Name: r.Name, Snake: r.Snake})
	}
	return out
}

// upsertMarkerBlock 用 block 替换 src 中 markerBegin 与 markerEnd 之间的整块内容；
// 标记缺失时把 block 追加到文件末尾，从而绝不丢字手写内容。
// upsertMarkerBlock replaces everything between markerBegin and markerEnd in src
// with block; when the markers are missing the block is appended at the end, so
// hand-written content is never lost.
func upsertMarkerBlock(src, block string) string {
	src = strings.ReplaceAll(src, "\r\n", "\n")
	block = strings.TrimRight(strings.ReplaceAll(block, "\r\n", "\n"), "\n")

	begin := strings.Index(src, markerBegin)
	end := strings.Index(src, markerEnd)
	if begin >= 0 && end > begin {
		cut := end + len(markerEnd)
		if i := strings.IndexByte(src[cut:], '\n'); i >= 0 {
			cut += i + 1
		} else {
			cut = len(src)
		}
		return src[:begin] + block + "\n" + src[cut:]
	}

	trimmed := strings.TrimRight(src, "\n")
	if trimmed != "" {
		trimmed += "\n\n"
	}
	return trimmed + block + "\n"
}

// formatSource 用 go/format 格式化生成源码，失败时把语法错误连同路径一起返回。
// formatSource formats generated source with go/format and reports a syntax error together with its path.
func formatSource(rel string, src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, errs.WrapDetail(err, ErrFormat, "path=%[1]s | 路径=%[1]s", rel)
	}
	return out, nil
}

// diffSummary 返回 old 与 new 之间的近似增删行数，形如 "+12/-3"。
// diffSummary returns the approximate number of added and removed lines between
// old and new, shaped as "+12/-3".
//
// 它是前缀/后缀之外的差异行数，用于 DryRun 摘要而非精确 diff。
// It counts the differing lines outside the common prefix and suffix, so it is a
// DryRun summary rather than an exact diff.
func diffSummary(old, new []byte) string {
	oldLines := splitLines(old)
	newLines := splitLines(new)

	prefix := 0
	for prefix < len(oldLines) && prefix < len(newLines) && oldLines[prefix] == newLines[prefix] {
		prefix++
	}
	suffix := 0
	for suffix < len(oldLines)-prefix && suffix < len(newLines)-prefix &&
		oldLines[len(oldLines)-1-suffix] == newLines[len(newLines)-1-suffix] {
		suffix++
	}
	return fmt.Sprintf("+%d/-%d", len(newLines)-prefix-suffix, len(oldLines)-prefix-suffix)
}

// splitLines 把内容拆成行，忽略行尾空行与 CRLF 差异。
// splitLines splits content into lines, ignoring a trailing empty line and CRLF differences.
func splitLines(b []byte) []string {
	if len(b) == 0 {
		return nil
	}
	s := strings.ReplaceAll(string(b), "\r\n", "\n")
	s = strings.TrimSuffix(s, "\n")
	return strings.Split(s, "\n")
}

// sortedKeys 返回 map 的键排序结果，用于生成顺序稳定的代码。
// sortedKeys returns the sorted keys of a map, keeping generated code order stable.
func sortedKeys[T any](m map[string]T) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
